  // '#' = основной цвет, '.' = прозрачно, 'o' = контур, 'x' = акцент.
  function bake(rows, color, accent) {
    const c = color || "currentColor";
    const a = accent || "#f8d860";
    const size = rows.length;
    let rects = "";
    for (let y = 0; y < size; y++) {
      for (let x = 0; x < size; x++) {
        const ch = rows[y][x];
        if (ch === ".") continue;
        const fill = ch === "o" ? "#000" : ch === "x" ? a : c;
        rects += '<rect x="' + x + '" y="' + y + '" width="1" height="1" fill="' + fill + '"/>';
      }
    }
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + size + ' ' + size + '" width="14" height="14" shape-rendering="crispEdges">' + rects + '</svg>';
  }

